function M.load(mode)
  local c = M.palettes[mode]
  if vim.g.colors_name then
    vim.cmd.hi("clear")
  end
  vim.o.background = mode
  vim.o.termguicolors = true
  vim.g.colors_name = mode == "light" and "cozybox-light" or "cozybox"

  for name, hl in pairs(groups(c, mode)) do
    vim.api.nvim_set_hl(0, name, hl)
  end
  for i, color in ipairs(c.terminal) do
    vim.g["terminal_color_" .. (i - 1)] = color
  end
end

return M
